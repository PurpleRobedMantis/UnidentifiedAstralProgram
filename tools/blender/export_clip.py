# Writes the keyed joints of a grey clip (.blend) to a game module, js/clips/<name>.js.
#   blender -b anim/grey-putdown.blend -P tools/blender/export_clip.py -- js/clips/grey-putdown.js grey-putdown
# Every joint that has keys is sampled at every frame (30 fps, frame 1 = 0 s), so whatever curve is drawn in Blender is
# what plays. Rotations become 'quaternion' tracks (x, y, z, w as three.js wants), root's location a 'vector' track. The
# scene's timeline markers become `marks` (seconds), which the game uses for its timing.
# Clips play in place: the game moves the grey (walkPath), so a clip's root may shift and lean during the move but must
# end where it started across the floor. The export refuses a clip whose root ends more than 1 cm from its start
# horizontally (pass --allow-drift after the name to override), and prints the root's largest horizontal offset.
import bpy, sys, json

argv = sys.argv[sys.argv.index('--') + 1:]
out, name = argv[0], argv[1]
allow_drift = '--allow-drift' in argv[2:]
sc = bpy.context.scene
fps = sc.render.fps

def fcurves(action):
    try: return list(action.fcurves)          # older Blender
    except AttributeError: pass
    res = []
    for layer in action.layers:
        for strip in layer.strips:
            for bag in strip.channelbags: res += list(bag.fcurves)
    return res

anim = {}
for o in bpy.data.objects:
    ad = o.animation_data
    if not ad or not ad.action: continue
    paths = {fc.data_path for fc in fcurves(ad.action)}
    anim[o.name] = paths
frames = list(range(sc.frame_start, sc.frame_end + 1))
tracks = {}
for f in frames:
    sc.frame_set(f)
    for nm, paths in anim.items():
        o = bpy.data.objects[nm]
        if 'rotation_quaternion' in paths:
            q = o.rotation_quaternion.normalized(); tr = tracks.setdefault(nm + '.quaternion', {'type': 'quaternion', 'v': []})
            v = [q.x, q.y, q.z, q.w]
            if tr['v'] and sum(a * b for a, b in zip(v, tr['v'][-4:])) < 0: v = [-c for c in v]   # same hemisphere as last
            tr['v'] += v
        if 'location' in paths:
            tracks.setdefault(nm + '.position', {'type': 'vector', 'v': []})['v'] += list(o.location)
times = [round((f - 1) / fps, 5) for f in frames]
# in place: the joints are children of the rotated UAP_world empty, so location is in the game's frame (y up, x/z floor)
rp = tracks.get('root.position')
if rp:
    v = rp['v']; pts = [(v[i], v[i + 2]) for i in range(0, len(v), 3)]
    end = ((pts[-1][0] - pts[0][0]) ** 2 + (pts[-1][1] - pts[0][1]) ** 2) ** 0.5
    far = max(((x - pts[0][0]) ** 2 + (z - pts[0][1]) ** 2) ** 0.5 for x, z in pts)
    print('root drift: ends %.1f cm from its start across the floor, at most %.1f cm away during the clip' % (end * 100, far * 100))
    if end > 0.01 and not allow_drift:
        sys.exit('REFUSED: the root does not end where it started (in-place clips only; --allow-drift to override). Nothing written.')
print('tracks:', ', '.join(sorted(tracks)))
clip = {
    'name': name, 'duration': times[-1], 'fps': fps,
    'marks': {m.name: round((m.frame - 1) / fps, 5) for m in sorted(sc.timeline_markers, key=lambda m: m.frame)},
    'tracks': [{'name': k, 'type': t['type'], 'times': times, 'values': [round(x, 5) for x in t['v']]} for k, t in sorted(tracks.items())],
}
with open(out, 'w', newline='\n') as fh:
    fh.write('// Generated by tools/blender/export_clip.py from anim/%s.blend: do not edit by hand. Edit the .blend in Blender\n' % name)
    fh.write('// and export again. Joint names are the grey\'s userData handles; times in seconds; marks set the game\'s timing.\n')
    fh.write('export default ' + json.dumps(clip, separators=(',', ':')) + ';\n')
print('wrote', out, len(tracks), 'tracks', len(frames), 'frames', clip['marks'])
