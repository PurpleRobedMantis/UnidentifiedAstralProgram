// Lists every on-screen caption, in source order, for review: subtitles (say / flashSub), hints, choices,
// line lists spoken by a character, the ending cards, and the jester lines.
//   node tools/captions.js            -> writes docs/CAPTIONS.md
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const STR = String.raw`'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"|` + '`(?:\\\\.|[^`\\\\])*`';
const lit = (s) => { try { return Function('return ' + s)(); } catch (_) { return s.slice(1, -1); } };
const strs = (s) => [...s.matchAll(new RegExp(STR, 'g'))].map((m) => lit(m[0]));
const WHO = { self: '', them: 'THEM', jest: 'JESTER' };

const FILES = [['js/scenes/night.js', 'Night: bedroom, the beam, the exam'], ['js/scenes/ship.js', 'Ship: hub and rooms'], ['js/scenes/control.js', 'Control room: the loom, the weather, the link, the return'], ['js/scenes/field.js', 'The field: the ride-along'], ['js/scenes/reveal.js', 'The reveal: the child and the memories'], ['js/scenes/beyond.js', 'Beyond: palace, mandala, endings']];
let out = '# Every caption\n\nGenerated by `node tools/captions.js` from the source, in the order it appears in each file (roughly play order).\n' +
  'Line numbers point at the source so a caption can be found and changed. THEM / JESTER mark who speaks; unmarked lines are narration or the player.\n';
let count = 0;
for (const [file, title] of FILES) {
  const whole = fs.readFileSync(path.join(root, file), 'utf8'), src = whole.split('\n');
  // any list read out by a caption call, e.g. say(walkLines[i]): its bare string lines are captions (build 132: the
  // mandala walk lines were missing because only literal arguments were read)
  const spoken = new Set([...whole.matchAll(/\b(?:say|flashSub)\(\s*(?:tr\()?(\w+)\[/g)].map((m) => m[1]));
  const LISTSTART = spoken.size ? new RegExp(String.raw`\b(${[...spoken].join('|')}) = \[`) : null;
  out += `\n## ${title} — \`${file}\`\n\n`;
  let inList = false;
  src.forEach((ln, i) => {
    const at = `\`${i + 1}\``, rows = [];
    for (const m of ln.matchAll(new RegExp(String.raw`\b(say|flashSub)\(\s*(${STR})(?:\s*,\s*(${STR}))?`, 'g'))) {
      const who = m[3] ? WHO[lit(m[3])] ?? lit(m[3]).toUpperCase() : (m[1] === 'flashSub' ? 'THEM' : '');
      rows.push((who ? `**${who}:** ` : '') + lit(m[2]));
    }
    for (const m of ln.matchAll(new RegExp(String.raw`\bhint\(\s*(${STR})`, 'g'))) if (lit(m[1])) rows.push('*hint:* ' + lit(m[1]));
    for (const m of ln.matchAll(new RegExp(String.raw`\bprompt\(\s*(${STR})`, 'g'))) if (lit(m[1])) rows.push('*prompt:* ' + lit(m[1]));
    // hub hints built in a variable (h = ...): every string on the line; ${...} parts show as {...}
    if (file.endsWith('ship.js') && /\b(let )?h = .*['"`]/.test(ln)) for (const m of ln.matchAll(new RegExp(STR, 'g'))) if (/\s/.test(m[0])) rows.push('*hint:* ' + m[0].slice(1, -1).replace(/\$\{/g, '{'));
    for (const m of ln.matchAll(/\bchoose\(\[(.*?)\]\)/g)) rows.push('*choice:* ' + strs(m[1]).map((s) => `[${s}]`).join(' · '));
    // [text, who] pairs in a list of lines (e.g. the mantis's repeat talks)
    for (const m of ln.matchAll(new RegExp(String.raw`^\s*\[\s*(${STR})\s*,\s*'(them|self|jest)'\s*\]`, 'g'))) rows.push((WHO[m[2]] ? `**${WHO[m[2]]}:** ` : '') + lit(m[1]));
    // plain string lists said one by one (see `spoken` above); [text, who] lists are handled below
    const ls = LISTSTART && ln.match(LISTSTART);
    if (ls && !/frags = \[/.test(ln)) { const rest = ln.slice(ls.index + ls[0].length); if (!/^\s*\[/.test(rest)) { for (const s of strs(rest.split(']')[0])) rows.push(s); inList = !/\]/.test(rest); } }
    else if (inList) { if (!/^\s*\[/.test(ln)) for (const s of strs(ln.split(']')[0])) rows.push(s); if (/\]\s*;?\s*$/.test(ln) && !/^\s*\[/.test(ln)) inList = false; }
    // ending cards
    const end = ln.match(/^\s*(\w+): \{ title: (.*?), text: (.*?), echo: (.*?)(?:, \w+:.*)? \},?$/);
    if (end) rows.push(`*ending card:* **${lit(end[2])}** — ${lit(end[3])}  \n  *echo:* ${lit(end[4])}`);
    const fr = ln.match(/frags = \[(.*?)\]/);
    if (fr) rows.push('*flashed words (random, upper case):* ' + [...new Set(strs(fr[1]))].join(' · '));
    for (const r of rows) { out += `- ${at} ${r}\n`; count++; }
  });
}
const jl = fs.readFileSync(path.join(root, 'js/jester-lines.txt'), 'utf8').split('\n').map((s) => s.trim()).filter(Boolean);
out += `\n## Jester shouts (random, in the palace) — \`js/jester-lines.txt\`\n\n` + jl.map((s) => `- ${s}`).join('\n') + '\n';
count += jl.length;
fs.writeFileSync(path.join(root, 'docs/CAPTIONS.md'), out);
console.log('docs/CAPTIONS.md:', count, 'captions');
